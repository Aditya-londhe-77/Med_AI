"""
Medical Pydantic Schemas for AISIA — AI_Based_Strategic_Intelligence_Assistant
Defines data models for medical queries, findings, citations, and reports.
"""

from typing import List, Optional, Any, Dict
from pydantic import BaseModel, Field
from datetime import datetime
from enum import Enum


class EvidenceGrade(str, Enum):
    """Evidence quality grading based on study design (adapted from Oxford CEBM)."""
    GRADE_A = "Grade A"   # Systematic reviews / RCTs / Official Guidelines
    GRADE_B = "Grade B"   # Cohort studies / Case-control / Reputable clinical sources
    GRADE_C = "Grade C"   # Expert opinion / Case reports / Educational content


class MedicalDomain(str, Enum):
    CARDIOLOGY = "Cardiology"
    NEUROLOGY = "Neurology"
    ONCOLOGY = "Oncology"
    PHARMACOLOGY = "Pharmacology"
    ENDOCRINOLOGY = "Endocrinology"
    PULMONOLOGY = "Pulmonology"
    GASTROENTEROLOGY = "Gastroenterology"
    ANATOMY = "Anatomy & Physiology"
    PSYCHIATRY = "Psychiatry"
    INFECTIOUS_DISEASE = "Infectious Disease"
    NEPHROLOGY = "Nephrology"
    ORTHOPEDICS = "Orthopedics"
    DERMATOLOGY = "Dermatology"
    GENERAL_MEDICINE = "General Medicine"
    PEDIATRICS = "Pediatrics"
    OBSTETRICS = "Obstetrics & Gynecology"
    EMERGENCY = "Emergency Medicine"
    UNKNOWN = "General Healthcare"


class MedicalSourceCitation(BaseModel):
    """A medical evidence source citation."""
    id: str
    url: Optional[str] = None
    title: str
    source_type: str = "Medical Reference"   # e.g., "WHO Guideline", "PubMed Abstract"
    grade: EvidenceGrade = EvidenceGrade.GRADE_B
    authors: Optional[str] = None
    publication_year: Optional[int] = None
    journal: Optional[str] = None
    snippet: str = ""
    is_ai_generated: bool = False  # True if no real primary source was found
    accessed_at: datetime = Field(default_factory=datetime.utcnow)


class MedicalFinding(BaseModel):
    """A single medical finding/claim produced by an agent."""
    id: str
    statement: str
    confidence_score: float = Field(ge=0.0, le=1.0)
    sources: List[MedicalSourceCitation] = []
    domain: MedicalDomain = MedicalDomain.GENERAL_MEDICINE
    agent_id: str
    finding_type: str = "informational"   # informational, diagnostic_clue, medication_info, anatomy
    contradictions: List[str] = []        # List of contradicting findings (IDs)
    validated: bool = False
    validation_notes: Optional[str] = None
    disclaimer: str = (
        "This information is for educational purposes only and does not constitute medical advice. "
        "Consult a qualified healthcare professional for diagnosis and treatment."
    )


class MedicalQueryRequest(BaseModel):
    """Request model for medical queries."""
    query: str
    session_id: str
    max_validation_rounds: int = Field(default=1, ge=1, le=3)
    requested_domains: List[str] = []   # Optional: specify which domains to focus on
    include_medication_info: bool = True
    include_clinical_analysis: bool = True
    selected_agents: Optional[List[str]] = None


class MedicalAgentResponse(BaseModel):
    """Response from a single medical agent."""
    agent_id: str
    agent_name: str
    status: str
    findings: List[MedicalFinding] = []
    raw_output: str = ""
    execution_time_ms: int = 0
    domain: MedicalDomain = MedicalDomain.GENERAL_MEDICINE


class MedicalReportSection(BaseModel):
    """A section of the final medical report."""
    title: str
    content: str
    section_type: str   # "overview", "clinical_info", "medication", "evidence", "safety"
    citations: List[str] = []  # Citation IDs


class MedicalReport(BaseModel):
    """The final structured medical report."""
    title: str
    query: str
    session_id: str
    executive_summary: str
    medical_domains: List[str] = []
    sections: List[MedicalReportSection] = []
    key_findings: List[str] = []
    evidence_summary: Dict[str, Any] = {}
    contradictions_noted: List[str] = []
    evidence_gaps: List[str] = []
    all_citations: List[MedicalSourceCitation] = []
    overall_confidence: float = 0.0
    safety_disclaimer: str = (
        "IMPORTANT: This report is generated by AI for educational and informational purposes only. "
        "It does NOT constitute medical advice, diagnosis, or treatment. "
        "Always consult a qualified healthcare professional before making medical decisions. "
        "In an emergency, call your local emergency services immediately."
    )
    emergency_warning: Optional[str] = None
    generated_at: datetime = Field(default_factory=datetime.utcnow)
    analysis_mode: str = "gemini"


class MedicalOrchestratorState(dict):
    """Type-safe state for the medical LangGraph orchestrator."""
    pass


class WSMedicalEvent(BaseModel):
    """WebSocket event for medical agent progress."""
    event_type: str   # agent_started, agent_finding, evidence_validated, synthesis_complete
    agent_id: Optional[str] = None
    agent_name: Optional[str] = None
    payload: Dict[str, Any] = {}
    timestamp: datetime = Field(default_factory=datetime.utcnow)
